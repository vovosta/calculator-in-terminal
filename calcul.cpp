#include <iostream>
#include "calcul.h"

// Here is the function to do addition
double addition (double a, double b){
	return a + b;
}
// Here is the function to the subtraction
double subtraction (double a, double b){
	return a - b;
}
// Here is the function for the multiplication
double multiplication (double a, double b){
	return a * b;
}
// Here is the function for the division 
double division (double a, double b){
	return a / b;
}
